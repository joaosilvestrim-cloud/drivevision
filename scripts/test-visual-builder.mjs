import { strict as assert } from 'node:assert';
import { parseCSV,defaultConfig } from '../lib/analytics.ts';
import { initialVisuals,makeVisual,visualData,boardRows,reorderVisuals,requestVisual } from '../lib/visual-builder.ts';
const source=parseCSV('Data;Região;Receita\n2026-08-01;Sul;10\n2026-09-01;Sul;20\n2026-09-02;Norte;30\n2026-09-03;Norte;','test.csv','test');
const config={...defaultConfig(source),dimension:'Região'};
const visuals=initialVisuals(source,config);
assert.equal(visuals.length,5);
assert.deepEqual(initialVisuals(source,{...config,visuals:[]}),[]);
const area=makeVisual('area',source,config,'area');
assert.deepEqual(visualData(source.rows,source,area).groups.map(g=>g.value),[10,50]);
const average={...makeVisual('kpi',source,config,'avg'),aggregation:'average'};
assert.equal(visualData(source.rows,source,average).value,20);
const filtered=boardRows(source,{...config,period:'30',filter:{field:'Região',value:'Sul'}});
assert.equal(filtered.length,1);
assert.equal(visualData(filtered,source,average).value,20);
const moved=reorderVisuals(visuals,visuals[0].id,visuals[2].id);
assert.equal(moved[2].id,visuals[0].id);
assert.equal(visuals[0].id,'initial-total');
const custom={...config,visuals:visuals.map(v=>({...v,color:'#8056da'}))};
const command=requestVisual('Adicione uma rosca de Receita por Região',source,custom,'added');
assert.equal(command.config.visuals.length,6);
assert.equal(command.config.visuals[5].type,'donut');
assert.equal(command.config.visuals[5].dimension,'Região');
assert.equal(command.config.visuals[0].color,'#8056da');
const period=requestVisual('Últimos 30 dias',source,custom,'unused');
assert.equal(period.config.period,'30');
assert.deepEqual(period.config.visuals,custom.visuals);
assert.equal(requestVisual('Adicione uma rosca por Campo inexistente',source,config,'bad').changed,false);
const negative=parseCSV('Grupo;Valor\nA;-10\nB;20','negative.csv','negative');
assert.equal(visualData(negative.rows,negative,makeVisual('donut',negative,defaultConfig(negative),'negative')).negative,true);
const persist=JSON.parse(JSON.stringify({...config,visuals:moved,appearance:{accent:'#8056da',mode:'dark',spacing:'compact',rounded:false},filter:{field:'Região',value:'Sul'}}));
assert.deepEqual(initialVisuals(source,persist),moved);
console.log('PASS visual editor: migration, empty canvas, monthly grouping, missing values, combined filters, reorder, independent configuration, guided requests, negative values, serialization');
